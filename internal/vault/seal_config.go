package vault

import (
	"bytes"
	"context"
	"encoding/base64"
	"encoding/json"
	"errors"
	"fmt"

	"github.com/ProtonMail/go-crypto/openpgp"
	"github.com/ProtonMail/go-crypto/openpgp/packet"
	"github.com/openbao/openbao/sdk/v2/helper/shamir"
	"github.com/openbao/openbao/sdk/v2/physical"
)

type ShamirPurpose string

const (
	Primary  ShamirPurpose = "primary"
	Recovery ShamirPurpose = "recovery"
)

// SealConfig is used to describe the shamir seal configuration.
type SealConfig struct {
	// Deprecated: Type is retained for legacy storage compatibility, provider
	// validation and seal migration detection.
	// Use Purpose to identify the Shamir configuration's role instead.
	Type string `json:"type" mapstructure:"type"`

	// Name of the seal to differ between emergency and primary seals.
	Name string `json:"name" mapstructure:"name"`

	// Purpose of the shamir seal.
	Purpose ShamirPurpose `json:"purpose" mapstructure:"purpose"`

	// SecretShares is the number of shares the secret is split into.
	// This is the N value of Shamir.
	SecretShares int `json:"secret_shares" mapstructure:"secret_shares"`

	// SecretThreshold is the number of shares required to reconstruct
	// the primary unseal key or recovery key.
	// This is the T value of Shamir.
	SecretThreshold int `json:"secret_threshold" mapstructure:"secret_threshold"`

	// PGPKeys contains public PGP keys used to encrypt the generated shares.
	// When provided, its length must equal SecretShares. Each key encrypts
	// the share at the corresponding index, so key order is important.
	PGPKeys []string `json:"pgp_keys" mapstructure:"pgp_keys"`

	// Nonce is a nonce generated by Vault used to ensure that when unseal keys
	// are submitted for a rotation, the operation itself is the one intended.
	Nonce string `json:"nonce" mapstructure:"nonce"`

	// Backup flag requests storage of PGP-encrypted shares at coreBarrierUnsealKeysBackupPath
	// or coreRecoveryUnsealKeysBackupPath. The backup is written before any required
	// verification completes.
	Backup bool `json:"backup" mapstructure:"backup"`

	// Stores the progress of the rotation (key shares).
	RotationProgress shamir.Shares `json:"-"`

	// VerificationRequired indicates that after a rotation validation must be
	// performed (via providing shares from the new key) before the new key is
	// actually installed. This is omitted from JSON as we don't persist the
	// new key, it lives only in memory.
	VerificationRequired bool `json:"-"`

	// VerificationKey is the new key that we will move to after successful
	// validation.
	VerificationKey []byte `json:"-"`

	// VerificationNonce stores the current operation nonce for verification.
	VerificationNonce string `json:"-"`

	// Stores the progress of the verification operation (key shares).
	VerificationProgress shamir.Shares `json:"-"`
}

// Validate is used to sanity check the seal configuration. Allows zero-share recovery
// configuration, needed when initializing auto-unseal without recovery keys.
func (s *SealConfig) Validate() error {
	if s.Purpose == Primary {
		if s.SecretShares < 1 {
			return errors.New("shares must be at least one")
		}
		if s.SecretThreshold < 1 {
			return errors.New("threshold must be at least one")
		}
	}

	return s.baseValidation()
}

// ValidateRotation is used to sanity check the seal configuration. Requires
// >0 shares and threshold, because the operation generates usable new shares.
func (s *SealConfig) ValidateRotation() error {
	if s.SecretShares < 1 {
		return errors.New("shares must be at least one")
	}
	if s.SecretThreshold < 1 {
		return errors.New("threshold must be at least one")
	}

	return s.baseValidation()
}

func (s *SealConfig) baseValidation() error {
	if s.SecretShares > 1 && s.SecretThreshold < 2 {
		return errors.New("threshold must be greater than one for multiple shares")
	}
	if s.SecretShares > 255 {
		return errors.New("shares must be less than 256")
	}
	if s.SecretThreshold > 255 {
		return errors.New("threshold must be less than 256")
	}
	if s.SecretThreshold > s.SecretShares {
		return errors.New("threshold cannot be larger than shares")
	}
	if len(s.PGPKeys) > 0 {
		if len(s.PGPKeys) != s.SecretShares {
			return errors.New("count mismatch between number of provided PGP keys and number of shares")
		}
		for _, keystring := range s.PGPKeys {
			data, err := base64.StdEncoding.DecodeString(keystring)
			if err != nil {
				return fmt.Errorf("error decoding given PGP key: %w", err)
			}
			_, err = openpgp.ReadEntity(packet.NewReader(bytes.NewBuffer(data)))
			if err != nil {
				return fmt.Errorf("error parsing given PGP key: %w", err)
			}
		}
	}
	return nil
}

func (s *SealConfig) Clone() *SealConfig {
	ret := &SealConfig{
		Type:                 s.Type,
		Name:                 s.Name,
		Purpose:              s.Purpose,
		SecretShares:         s.SecretShares,
		SecretThreshold:      s.SecretThreshold,
		Nonce:                s.Nonce,
		Backup:               s.Backup,
		VerificationRequired: s.VerificationRequired,
		VerificationNonce:    s.VerificationNonce,
	}
	if len(s.PGPKeys) > 0 {
		ret.PGPKeys = make([]string, len(s.PGPKeys))
		copy(ret.PGPKeys, s.PGPKeys)
	}
	if len(s.VerificationKey) > 0 {
		ret.VerificationKey = make([]byte, len(s.VerificationKey))
		copy(ret.VerificationKey, s.VerificationKey)
	}
	return ret
}

// writeLegacyBarrierConfigOnAutoUnseal writes a provider-typed barrier
// configuration for compatibility with older binaries when using auto-unseal.
// The share parameters are stubs, actual recovery configuration is stored separately.
func (c *Core) writeLegacyBarrierConfigOnAutoUnseal(ctx context.Context) error {
	legacySealConfig := &SealConfig{
		Type:            c.seal.WrapperType().String(),
		SecretShares:    1,
		SecretThreshold: 1,
	}

	buf, err := json.Marshal(legacySealConfig)
	if err != nil {
		return fmt.Errorf("failed to marshal legacy (barrier) seal configuration: %w", err)
	}

	if err := c.physical.Put(ctx, &physical.Entry{
		Key:   barrierSealConfigPath,
		Value: buf,
	}); err != nil {
		c.logger.Error("failed to write legacy (barrier) seal configuration", "error", err)
		return fmt.Errorf("failed to write legacy (barrier) seal configuration: %w", err)
	}

	return nil
}
